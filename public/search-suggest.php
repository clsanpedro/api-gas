<?php

declare(strict_types=1);


/*
 * ============================================================
 * INICIO: DEPENDENCIAS
 * ============================================================
 */

require_once __DIR__
  . '/../app/search-data.php';

/*
 * ============================================================
 * FIN: DEPENDENCIAS
 * ============================================================
 */


/*
 * ============================================================
 * INICIO: CABECERAS
 * ============================================================
 */

header(
  'Content-Type: application/json; charset=utf-8'
);

header(
  'Cache-Control: no-store, no-cache, must-revalidate'
);

/*
 * ============================================================
 * FIN: CABECERAS
 * ============================================================
 */


/*
 * ============================================================
 * INICIO: CONSULTA
 * ============================================================
 */

$query =
  normalizeSearchQuery(
    (string) (
      $_GET['q']
      ?? ''
    )
  );


if (
  $query === ''
  || mb_strlen(
    $query,
    'UTF-8'
  ) < 2
) {

  echo json_encode(
    [
      'query' =>
      $query,

      'results' =>
      [],
    ],
    JSON_UNESCAPED_UNICODE
      | JSON_UNESCAPED_SLASHES
  );

  exit;
}


$results =
  searchSuggestions(
    $pdo,
    $query,
    8
  );

/*
 * ============================================================
 * FIN: CONSULTA
 * ============================================================
 */


/*
 * ============================================================
 * INICIO: RESPUESTA
 * ============================================================
 */

echo json_encode(
  [
    'query' =>
    $query,

    'results' =>
    $results,
  ],
  JSON_UNESCAPED_UNICODE
    | JSON_UNESCAPED_SLASHES
);

/*
 * ============================================================
 * FIN: RESPUESTA
 * ============================================================
 */